type DeepTranslations<T> = {
  readonly [K in keyof T]: T[K] extends (...args: infer Args) => infer Ret
    ? (...args: Args) => Ret
    : T[K] extends object
    ? DeepTranslations<T[K]>
    : string;
};

export type Translations = DeepTranslations<typeof translations.ru>;
